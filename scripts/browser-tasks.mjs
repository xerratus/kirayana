const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
import assert from 'node:assert/strict'
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[]
 page.on('pageerror',error=>errors.push(error.message))
 await page.goto('http://127.0.0.1:5180');await page.waitForTimeout(800)
 await page.getByRole('button',{name:'Add Tasks to You',exact:true}).focus();await page.keyboard.press('Enter')
 const dialog=page.getByRole('dialog')
 await dialog.getByRole('textbox',{name:'Name',exact:true}).fill('Tasks')
 await dialog.getByRole('button',{name:'Create Tasks',exact:true}).click();await page.waitForTimeout(700)
 await page.getByRole('button',{name:'Tasks details',exact:true}).focus();await page.keyboard.press('Enter');await page.waitForTimeout(500)
 const panel=page.getByRole('complementary',{name:'Tasks details',exact:true})
 const input=panel.getByRole('textbox',{name:'New task',exact:true})
 await input.focus()
 assert.equal(await input.evaluate(element=>getComputedStyle(element).outlineOffset),'-2px')
 const toggle=panel.getByRole('switch',{name:'Show completed (0)',exact:true})
 await toggle.focus();await page.keyboard.press('Space');assert.equal(await toggle.isChecked(),true)
 await page.keyboard.press('Space');assert.equal(await toggle.isChecked(),false)
 await input.fill('Test task')
 await input.press('Enter');await page.waitForTimeout(300)
 const row=panel.getByRole('listitem').filter({hasText:'Test task'})
 await page.mouse.move(5,5)
 assert.equal(await row.locator('.kirayana-task-actions').evaluate(el=>getComputedStyle(el).opacity),'0')
 await row.hover();await page.waitForTimeout(150)
 assert.equal(await row.locator('.kirayana-task-actions').evaluate(el=>getComputedStyle(el).opacity),'1')
 await row.getByRole('button',{name:'Complete Test task',exact:true}).click()
 assert.equal(await panel.getByText('Test task',{exact:true}).count(),0)
 await panel.getByRole('switch',{name:'Show completed (1)',exact:true}).check()
 await panel.getByRole('button',{name:'Restore Test task',exact:true}).focus();await page.keyboard.press('Enter')
 await page.waitForTimeout(600);await page.reload();await page.waitForTimeout(900)
 const restored=page.getByRole('complementary',{name:'Tasks details',exact:true})
 assert.equal(await restored.getByText('Test task',{exact:true}).count(),1)
 await restored.getByRole('listitem').hover()
 await restored.getByRole('button',{name:'Delete Test task',exact:true}).click()
 await page.getByRole('dialog').getByRole('button',{name:'Delete task',exact:true}).click()
 assert.equal(await restored.getByText('Test task',{exact:true}).count(),0)
 assert.deepEqual(errors,[])
 console.log('Tasks passed: create list, add task, hover controls, complete/hide, show/restore, persistence, and delete.')
} finally { await browser.close() }
